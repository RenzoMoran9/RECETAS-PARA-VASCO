// Abre la app en tamaño celular, recorre las pantallas, saca capturas y reporta errores.
import { createRequire } from 'node:module';
import path from 'node:path';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.argv[2] || 'http://localhost:8765/';
const out = process.argv[3] || '.';
const scheme = process.argv[4] || 'light';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: scheme, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
const shot = async (name, full = false) => page.screenshot({ path: path.join(out, `${scheme}-${name}.png`), fullPage: full });
const wait = (ms = 300) => page.waitForTimeout(ms);
await page.goto(base + '#menu');
await wait(700);
await shot('01-menu-vasco');
await page.click('[data-act=welcomed]');
await page.click('[data-act=perfil][data-p=papas]');
await wait();
await shot('02-menu-papas');
await shot('02-menu-papas-full', true);
await page.click('.slot[data-slot=almuerzo] [data-act=opciones]');
await wait();
await shot('03-opciones-papas');
await page.click('[data-act=close-sheet] >> nth=1');
await wait();
await page.click('.slot[data-slot=almuerzo] .slot-main');
await wait();
await shot('04-receta-papas-full', true);
await page.goto(base + '#recetas');
await wait();
await shot('05-recetas-papas');
await page.goto(base + '#refri');
await wait();
await shot('06-refri-vacio');
await page.fill('#refri-q', 'pol');
await wait(200);
await shot('07-refri-sugerencias');
await page.press('#refri-q', 'Enter');
await page.fill('#refri-q', 'papa');
await page.click('#refri-sug [data-act=refri-add] >> nth=0');
await page.fill('#refri-q', 'toma');
await page.press('#refri-q', 'Enter');
await wait();
await shot('08-refri-resultados');
await shot('08-refri-resultados-full', true);
await page.click('[data-act=refri-para][data-p=ambos]');
await wait();
await shot('09-refri-ambos-full', true);
const falta = page.locator('[data-act=refri-falta]').first();
if (await falta.count()) await falta.click();
await page.click('[data-act=refri-pick]');
await wait();
await shot('10-refri-dibujos');
await page.click('.sheet-foot [data-act=close-sheet]');
await page.goto(base + '#compras');
await wait();
await shot('11-compras-full', true);
await page.goto(base + '#guia');
await wait();
await shot('12-guia-papas-full', true);
await page.click('[data-act=perfil][data-p=vasco]');
await wait();
await shot('13-guia-vasco');
await page.goto(base + '#recetas');
await page.click('.card >> nth=0');
await wait();
await shot('14-receta-vasco-full', true);
await page.goto(base + '#ajustes');
await wait();
await shot('15-ajustes-full', true);
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
console.log('horizontal overflow:', overflow);
console.log(errors.length ? errors.join('\n') : 'sin errores');
await browser.close();
